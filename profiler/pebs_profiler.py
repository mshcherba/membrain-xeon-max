#!/usr/bin/env python3
"""
MemBrain In-Process PEBS Memory Profiler
Profiles memory allocation access frequency and physical Peak RSS per site_id
using hardware PEBS circular buffers and /proc/self/pagemap in-process.
"""

import os
import sys
import time
import json
import shutil
import subprocess
import argparse

def run_pebs_profiling(cmd, runtime_lib, sites_file, output_file, sample_period=512, sample_interval=0.5):
    runtime_abs = os.path.abspath(runtime_lib)
    if not os.path.exists(runtime_abs):
        print(f"[PEBS Profiler] Error: Runtime library '{runtime_abs}' not found!", file=sys.stderr)
        sys.exit(1)

    # Cleanup old profile and trace files
    for old_file in ["profile_data.json", "site_rss_profile.json", "alloc_trace.txt", "pebs_perf.data"]:
        if os.path.exists(old_file):
            try:
                os.remove(old_file)
            except OSError:
                pass

    env = os.environ.copy()
    ld_preload = env.get("LD_PRELOAD", "")
    env["LD_PRELOAD"] = f"{runtime_abs}:{ld_preload}" if ld_preload else runtime_abs
    env["MEMBRAIN_PROFILE"] = "1"
    env["MEMBRAIN_SAMPLE_PERIOD"] = str(sample_period)
    env["MEMBRAIN_SITES_FILE"] = os.path.abspath(sites_file)
    env["MEMBRAIN_OUTPUT_PROFILE"] = os.path.abspath(output_file)
    env["MEMBRAIN_VERBOSE"] = "1"

    print(f"[PEBS Profiler] Launching target command with in-process PEBS buffers (sample period={sample_period}): {' '.join(cmd)}", flush=True)
    start_time = time.time()

    try:
        proc = subprocess.Popen(cmd, env=env)
    except FileNotFoundError as e:
        print(f"[PEBS Profiler] Error: Failed to execute command: {e}", file=sys.stderr)
        sys.exit(1)

    peak_process_rss = 0
    page_size = os.sysconf('SC_PAGE_SIZE')

    def get_process_tree_rss(pid):
        total_rss = 0
        try:
            pids_to_check = [pid]
            while pids_to_check:
                curr_pid = pids_to_check.pop(0)
                try:
                    with open(f"/proc/{curr_pid}/statm", "r") as f:
                        pages = int(f.read().split()[1])
                        total_rss += pages * page_size
                except (FileNotFoundError, ProcessLookupError, IndexError):
                    pass

                try:
                    with open(f"/proc/{curr_pid}/task/{curr_pid}/children", "r") as f:
                        children = [int(c) for c in f.read().split()]
                        pids_to_check.extend(children)
                except (FileNotFoundError, ProcessLookupError, ValueError):
                    pass
        except Exception:
            pass
        return total_rss

    while proc.poll() is None:
        current_rss = get_process_tree_rss(proc.pid)
        if current_rss > peak_process_rss:
            peak_process_rss = current_rss
        time.sleep(sample_interval)

    ret_code = proc.wait()
    if ret_code != 0:
        print(f"[PEBS Profiler] Error: Target command failed with exit code {ret_code}.", file=sys.stderr)
        sys.exit(ret_code)

    elapsed = time.time() - start_time
    print(f"[PEBS Profiler] Target finished in {elapsed:.2f} seconds. Peak Process RSS: {peak_process_rss / (1024*1024):.2f} MB")

    if not os.path.exists(output_file):
        print(f"[PEBS Profiler] Error: '{output_file}' was not generated by libmembrain_rt.so!", file=sys.stderr)
        sys.exit(1)

    try:
        with open(output_file, "r") as f:
            data = json.load(f)
            print(f"[PEBS Profiler] Verified profile data for {len(data)} allocation sites in '{output_file}'")
    except Exception as e:
        print(f"[PEBS Profiler] Warning reading '{output_file}': {e}", file=sys.stderr)

def main():
    parser = argparse.ArgumentParser(description="MemBrain In-Process PEBS Memory Profiler")
    parser.add_argument("--sites", default="allocation_sites.json", help="Path to allocation_sites.json")
    parser.add_argument("--runtime", default="../build/runtime/libmembrain_rt.so", help="Path to libmembrain_rt.so")
    parser.add_argument("--output", default="profile_data.json", help="Output profile data JSON path")
    parser.add_argument("--sample-period", "--sample-rate", type=int, default=512, help="PEBS sample period/rate (LLC misses per sample, default: 512)")
    parser.add_argument("cmd", nargs=argparse.REMAINDER, help="Target application command")

    args = parser.parse_args()
    if not args.cmd:
        parser.print_help()
        sys.exit(1)

    run_pebs_profiling(args.cmd, args.runtime, args.sites, args.output, sample_period=args.sample_period)

if __name__ == "__main__":
    main()
